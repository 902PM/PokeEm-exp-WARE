#define HGSS_DARK_MODE                      FALSE // TRUEの場合、ダークモードを有効にします。
#define HGSS_HIDE_UNSEEN_EVOLUTION_NAMES    TRUE  // TRUEの場合、進化後のポケモンの名前を非表示にします。
#define HGSS_HIDE_UNOWNED_EVOLUTION_METHODS TRUE  // TRUEの場合、進化メソッドを非表示にします。
